import { describe, expect, it } from 'vitest'
import { continueSeries } from '../../src/lib/fillSeries.js'

// 표 편집기 자동 채우기(엑셀의 채우기 핸들)의 규칙. 씨앗(seed)이 되는 칸들의 글자를 받아 이어질 글자를 count 개 돌려준다.
// 규칙은 엑셀을 따른다: 숫자 두 개 이상이면 등차로 이어 가고, 숫자 하나는 그대로 복사(Ctrl 을 누르면 1씩 증가),
// "항목1" 같은 글자 속 숫자·날짜·요일·월 이름은 하나만 있어도 이어 가며(Ctrl 을 누르면 복사), 나머지는 씨앗을 반복한다.

const go = (seeds, count, options) => continueSeries(seeds, count, options)

describe('숫자', () => {
  it('두 개 이상이면 등차로 이어 간다', () => {
    expect(go(['1', '2'], 3)).toEqual(['3', '4', '5'])
    expect(go(['10', '20'], 2)).toEqual(['30', '40'])
    expect(go(['5', '3'], 3)).toEqual(['1', '-1', '-3'])
    expect(go(['1', '2', '3'], 2)).toEqual(['4', '5'])
  })

  it('하나뿐이면 그대로 복사한다 (엑셀과 같음)', () => {
    expect(go(['1'], 3)).toEqual(['1', '1', '1'])
  })

  it('Ctrl(invert)을 누르면 하나뿐인 숫자는 1씩 늘어난다', () => {
    expect(go(['1'], 3, { invert: true })).toEqual(['2', '3', '4'])
  })

  it('Ctrl(invert)을 누르면 두 개 이상인 숫자는 이어 가지 않고 씨앗을 반복한다', () => {
    expect(go(['1', '2'], 3, { invert: true })).toEqual(['1', '2', '1'])
  })

  it('등차가 아니면 씨앗을 반복한다', () => {
    expect(go(['1', '2', '4'], 4)).toEqual(['1', '2', '4', '1'])
  })

  it('같은 값만 있으면(차가 0) 그대로 반복한다', () => {
    expect(go(['5', '5'], 2)).toEqual(['5', '5'])
  })

  it('소수는 이진 소수 오차 없이 이어 간다', () => {
    expect(go(['0.1', '0.2'], 3)).toEqual(['0.3', '0.4', '0.5'])
    expect(go(['1.5', '2'], 2)).toEqual(['2.5', '3.0'])
  })

  it('소수 자릿수는 씨앗 중 가장 긴 쪽에 맞춘다 (1, 1.5 → 2.0, 2.5)', () => {
    expect(go(['1', '1.5'], 2)).toEqual(['2.0', '2.5'])
  })

  it('천 단위 쉼표를 유지한다', () => {
    expect(go(['1,000', '2,000'], 2)).toEqual(['3,000', '4,000'])
    expect(go(['998', '999'], 3)).toEqual(['1000', '1001', '1002'])
    expect(go(['1,998', '1,999'], 2)).toEqual(['2,000', '2,001'])
  })

  it('앞의 0(자릿수 맞춤)을 유지한다', () => {
    expect(go(['001', '002'], 3)).toEqual(['003', '004', '005'])
    expect(go(['009', '010'], 2)).toEqual(['011', '012'])
    expect(go(['007'], 2, { invert: true })).toEqual(['008', '009'])
  })

  it('씨앗의 앞뒤 공백은 무시한다', () => {
    expect(go([' 1', '2 '], 2)).toEqual(['3', '4'])
  })

  it('부호가 있는 숫자', () => {
    expect(go(['-2', '-1'], 3)).toEqual(['0', '1', '2'])
    expect(go(['+1', '+2'], 1)).toEqual(['3'])
  })
})

describe('글자 속 숫자 (항목1, 3호선, ₩500)', () => {
  it('하나뿐이어도 끝의 숫자를 1씩 늘린다', () => {
    expect(go(['항목1'], 3)).toEqual(['항목2', '항목3', '항목4'])
    expect(go(['1호선'], 2)).toEqual(['2호선', '3호선'])
    expect(go(['item9'], 2)).toEqual(['item10', 'item11'])
  })

  it('가장 뒤의 숫자를 늘린다', () => {
    expect(go(['v1.2.3'], 2)).toEqual(['v1.2.4', 'v1.2.5'])
    expect(go(['2팀 3조'], 2)).toEqual(['2팀 4조', '2팀 5조'])
  })

  it('하이픈은 부호가 아니다 (A-1 → A-2)', () => {
    expect(go(['A-1'], 3)).toEqual(['A-2', 'A-3', 'A-4'])
  })

  it('통화·쉼표·앞의 0 서식을 유지한다', () => {
    expect(go(['₩500'], 2)).toEqual(['₩501', '₩502'])
    expect(go(['1,200원'], 2)).toEqual(['1,201원', '1,202원'])
    expect(go(['No.001'], 2)).toEqual(['No.002', 'No.003'])
  })

  it('두 개 이상이면 숫자의 차로 이어 간다', () => {
    expect(go(['항목1', '항목3'], 2)).toEqual(['항목5', '항목7'])
  })

  it('순수 숫자와 글자 속 숫자가 섞이면 반복한다', () => {
    expect(go(['1', '항목2'], 3)).toEqual(['1', '항목2', '1'])
  })

  it('앞뒤 글자가 다르면 씨앗을 반복한다', () => {
    expect(go(['a1', 'b2'], 3)).toEqual(['a1', 'b2', 'a1'])
    expect(go(['1호', '2번'], 2)).toEqual(['1호', '2번'])
  })

  it('Ctrl(invert)을 누르면 하나뿐인 글자 속 숫자는 복사된다', () => {
    expect(go(['항목1'], 2, { invert: true })).toEqual(['항목1', '항목1'])
  })

  it('숫자가 없는 글자는 반복한다', () => {
    expect(go(['가나다'], 2)).toEqual(['가나다', '가나다'])
  })
})

describe('날짜', () => {
  it('하나뿐이어도 하루씩 이어 간다', () => {
    expect(go(['2024-01-05'], 3)).toEqual(['2024-01-06', '2024-01-07', '2024-01-08'])
  })

  it('달·해가 바뀌는 날과 윤년을 맞게 센다', () => {
    expect(go(['2024-01-31'], 2)).toEqual(['2024-02-01', '2024-02-02'])
    expect(go(['2024-02-28'], 3)).toEqual(['2024-02-29', '2024-03-01', '2024-03-02'])
    expect(go(['2023-02-28'], 2)).toEqual(['2023-03-01', '2023-03-02'])
    expect(go(['2024-12-31'], 2)).toEqual(['2025-01-01', '2025-01-02'])
  })

  it('구분 기호(. / 와 한글)와 앞의 0 없는 형식을 유지한다', () => {
    expect(go(['2024.01.05'], 2)).toEqual(['2024.01.06', '2024.01.07'])
    expect(go(['2024/01/05'], 1)).toEqual(['2024/01/06'])
    expect(go(['2024-1-5'], 2)).toEqual(['2024-1-6', '2024-1-7'])
    expect(go(['2024년 1월 5일'], 2)).toEqual(['2024년 1월 6일', '2024년 1월 7일'])
  })

  it('두 개 이상이면 날짜 차이(일)로 이어 간다', () => {
    expect(go(['2024-01-01', '2024-01-08'], 2)).toEqual(['2024-01-15', '2024-01-22'])
    expect(go(['2024-01-10', '2024-01-09'], 2)).toEqual(['2024-01-08', '2024-01-07'])
  })

  it('같은 날짜(일)에 달만 바뀌는 씨앗은 달 단위로 이어 간다', () => {
    expect(go(['2024-01-01', '2024-02-01'], 3)).toEqual(['2024-03-01', '2024-04-01', '2024-05-01'])
    expect(go(['2024-11-15', '2024-12-15'], 2)).toEqual(['2025-01-15', '2025-02-15'])
  })

  it('월·일이 두 자리면 앞의 0 없이도 두 자리로 맞춰 쓴다 (2024-10-30 → 2024-11-01)', () => {
    expect(go(['2024-10-30'], 3)).toEqual(['2024-10-31', '2024-11-01', '2024-11-02'])
  })

  it('달 단위로 이어 갈 때 그 달에 없는 일자는 말일로 맞춘다', () => {
    expect(go(['2024-12-31', '2025-01-31'], 3)).toEqual(['2025-02-28', '2025-03-31', '2025-04-30'])
  })

  it('없는 날짜는 날짜로 읽지 않는다', () => {
    expect(go(['2023-02-29'], 2)).toEqual(['2023-02-29', '2023-02-29'])
    expect(go(['2024-13-45'], 1)).toEqual(['2024-13-45'])
  })

  it('Ctrl(invert)을 누르면 복사된다', () => {
    expect(go(['2024-01-05'], 2, { invert: true })).toEqual(['2024-01-05', '2024-01-05'])
  })

  it('형식이 서로 다른 날짜 씨앗은 반복한다', () => {
    expect(go(['2024-01-05', '2024.01.06'], 3)).toEqual(['2024-01-05', '2024.01.06', '2024-01-05'])
  })
})

describe('요일·월 이름', () => {
  it('요일이 한 바퀴 돈다', () => {
    expect(go(['월'], 3)).toEqual(['화', '수', '목'])
    expect(go(['금'], 3)).toEqual(['토', '일', '월'])
    expect(go(['월요일'], 2)).toEqual(['화요일', '수요일'])
  })

  it('월이 한 바퀴 돈다 (1월 ~ 12월)', () => {
    expect(go(['1월'], 2)).toEqual(['2월', '3월'])
    expect(go(['11월'], 3)).toEqual(['12월', '1월', '2월'])
  })

  it('영문 요일·월은 쓴 글자꼴(대문자·소문자)을 따른다', () => {
    expect(go(['Mon'], 2)).toEqual(['Tue', 'Wed'])
    expect(go(['mon'], 2)).toEqual(['tue', 'wed'])
    expect(go(['MON'], 2)).toEqual(['TUE', 'WED'])
    expect(go(['Sun'], 2)).toEqual(['Mon', 'Tue'])
    expect(go(['January'], 2)).toEqual(['February', 'March'])
    expect(go(['Dec'], 2)).toEqual(['Jan', 'Feb'])
  })

  it('두 개 이상이면 간격을 이어 간다 (월, 수 → 금, 일)', () => {
    expect(go(['월', '수'], 3)).toEqual(['금', '일', '화'])
  })

  it('거꾸로 가는 간격도 이어 간다 (수, 월 → 토, 목)', () => {
    expect(go(['수', '월'], 2)).toEqual(['토', '목'])
  })

  it('같은 이름만 있거나 간격이 일정하지 않으면 반복한다', () => {
    expect(go(['월', '월'], 3)).toEqual(['월', '월', '월'])
    expect(go(['월', '수', '목'], 4)).toEqual(['월', '수', '목', '월'])
  })

  it('다른 묶음이 섞이면 반복한다', () => {
    expect(go(['월', 'Mon'], 3)).toEqual(['월', 'Mon', '월'])
  })

  it('Ctrl(invert)을 누르면 복사된다', () => {
    expect(go(['월'], 2, { invert: true })).toEqual(['월', '월'])
  })

  it('13월 같은 것은 월 이름이 아니라 글자 속 숫자다', () => {
    expect(go(['13월'], 2)).toEqual(['14월', '15월'])
  })
})

describe('그 밖: 씨앗 반복', () => {
  it('글자 하나는 그대로 복사', () => {
    expect(go(['a'], 3)).toEqual(['a', 'a', 'a'])
  })

  it('여러 개는 순서대로 반복', () => {
    expect(go(['a', 'b'], 5)).toEqual(['a', 'b', 'a', 'b', 'a'])
    expect(go(['가', '나', '다'], 4)).toEqual(['가', '나', '다', '가'])
  })

  it('숫자와 글자가 섞이면 반복한다', () => {
    expect(go(['1', 'a'], 3)).toEqual(['1', 'a', '1'])
  })

  it('빈 칸은 빈 칸으로 이어진다', () => {
    expect(go([''], 2)).toEqual(['', ''])
    expect(go(['1', ''], 3)).toEqual(['1', '', '1'])
  })

  it('복사할 때는 원래 글자(공백 포함)를 그대로 쓴다', () => {
    expect(go([' a '], 2)).toEqual([' a ', ' a '])
  })

  it('count 가 0 이하이면 빈 배열', () => {
    expect(go(['1', '2'], 0)).toEqual([])
    expect(go(['1', '2'], -3)).toEqual([])
  })

  it('씨앗이 없으면 빈 칸으로 채운다', () => {
    expect(go([], 2)).toEqual(['', ''])
  })
})

describe('backward - 위·왼쪽으로 끌 때 (이어 붙는 쪽부터 가까운 순서)', () => {
  const back = (seeds, count, options) => continueSeries(seeds, count, { ...options, backward: true })

  it('숫자 둘 이상: 씨앗이 앞에서 뒤로 늘어나는 방향의 반대로 이어 간다 (3, 4 → 2, 1, 0)', () => {
    expect(back(['3', '4'], 3)).toEqual(['2', '1', '0'])
    expect(back(['10', '20'], 2)).toEqual(['0', '-10'])
  })

  it('숫자 하나는 복사, Ctrl 이면 1씩 줄어든다', () => {
    expect(back(['7'], 2)).toEqual(['7', '7'])
    expect(back(['7'], 3, { invert: true })).toEqual(['6', '5', '4'])
  })

  it('글자 속 숫자 하나는 1씩 줄어든다', () => {
    expect(back(['항목5'], 3)).toEqual(['항목4', '항목3', '항목2'])
  })

  it('날짜 하나는 하루씩 거꾸로 (윤년·달 경계 포함)', () => {
    expect(back(['2024-03-01'], 2)).toEqual(['2024-02-29', '2024-02-28'])
    expect(back(['2024-01-01'], 1)).toEqual(['2023-12-31'])
  })

  it('날짜 둘: 같은 일자에 달만 다르면 달 단위로 거꾸로 (2/1, 3/1 → 1/1, 12/1)', () => {
    expect(back(['2024-02-01', '2024-03-01'], 2)).toEqual(['2024-01-01', '2023-12-01'])
  })

  it('요일·월 이름은 거꾸로 한 바퀴 돈다', () => {
    expect(back(['화'], 3)).toEqual(['월', '일', '토'])
    expect(back(['1월'], 2)).toEqual(['12월', '11월'])
    expect(back(['수', '목'], 3)).toEqual(['화', '월', '일'])
  })

  it('반복 씨앗은 이어 붙는 쪽(끝)부터 거꾸로 반복한다', () => {
    expect(back(['a', 'b'], 5)).toEqual(['b', 'a', 'b', 'a', 'b'])
    expect(back(['1', '2', '4'], 4)).toEqual(['4', '2', '1', '4'])
  })

  it('빈 칸·count 0 은 앞쪽과 같다', () => {
    expect(back([''], 2)).toEqual(['', ''])
    expect(back(['1', '2'], 0)).toEqual([])
  })
})
